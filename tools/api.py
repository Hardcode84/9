"""Publish the CRUST0 declarations for the compiler's selected C99 interface."""

import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
C_ONLY = {
    "crust_run_stage",
    "crust_alloc",
    "crust_grow_array",
    "crust_copy_string",
    "crust_intern",
    "crust_fail",
    "crust_map_set",
    "crust_resolve_type",
    "crust_pointer_type",
    "crust_type_equal",
}
SCALARS = {
    "void": "unit",
    "bool": "bool",
    "char": "u8",
    "unsigned char": "u8",
    "int32_t": "i32",
    "uint32_t": "u32",
    "uint64_t": "u64",
    "size_t": "usize",
    "uintptr_t": "usize",
    "unsigned": "u32",
}
OPAQUE = {"void", "FILE", "CrustArenaBlock", "CrustFailureFrame", "CrustEval", "CrustRunState"}


def publish(path, output, check):
    if path.exists() and path.read_text() == output:
        return
    if check:
        raise SystemExit(f"API declarations differ: {path.relative_to(ROOT)}; run tools/api.py")
    path.write_text(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    enums = {}
    headers = {}
    digest = hashlib.sha256(b"crust-native-api-v1-linux-x64-lp64\0")
    for stem in (
        "crust0",
        "crust0_host",
        "crust0_x64",
        "crust0_stage",
        "crust0_eval",
        "crust0_run",
    ):
        source = (ROOT / "include" / f"{stem}.h").read_text()
        source = source.replace("\\\n", "")
        source = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
        digest.update(stem.encode() + b"\0")
        digest.update(" ".join(re.findall(r"\w+|[^\s]", source)).encode() + b"\0")
        source = re.sub(r"^#.*$", "", source, flags=re.M)
        headers[stem] = source
        for body, name in re.findall(r"typedef enum\s*\{(.*?)\}\s*(\w+)\s*;", source, re.S):
            enums[name] = [value.strip() for value in body.split(",") if value.strip()]
            if any(not re.fullmatch(r"\w+", value) for value in enums[name]):
                raise ValueError(f"unsupported explicit enum value in {name}")

    abi = digest.hexdigest()
    names = ", ".join(f'"CRUST_ABI_{stem}"' for stem in headers)
    publish(
        ROOT / "include/crust0_abi.h",
        "/* SPDX-License-Identifier: Apache-2.0 */\n\n"
        "/* Generated by tools/api.py. */\n"
        "#ifndef CRUST0_ABI_H\n#define CRUST0_ABI_H\n\n"
        f'#define CRUST_ABI_DIGEST "{abi}"\n'
        "/* clang-format off */\n"
        f"#define CRUST_ABI_NAMES {{{names}}}\n"
        "/* clang-format on */\n"
        "/* Use once in a native library translation unit. */\n"
        "#define CRUST_ABI_EXPORT const char *const CRUST_ABI_crust0 = CRUST_ABI_DIGEST\n\n"
        "#endif\n",
        args.check,
    )

    def ctype(text):
        text = re.sub(r"\bconst\b", "", text)
        pointers = text.count("*")
        base = " ".join(text.replace("*", " ").split())
        if pointers and base in OPAQUE:
            base = "u8"
        elif base in SCALARS:
            base = SCALARS[base]
        elif base in enums:
            base = "u32"
        elif not re.fullmatch(r"Crust\w+", base):
            raise ValueError(f"unsupported interface type: {text}")
        return "*" * pointers + base

    def declaration(text):
        text = " ".join(text.split())
        callback = re.fullmatch(r"(.+?)\(\*(\w+)\)\((.*)\)", text)
        if callback:
            result, name, arguments = callback.groups()
            types = (
                [declaration(arg)[1] for arg in arguments.split(",")] if arguments != "void" else []
            )
            return name, f"fn({', '.join(types)}) -> {ctype(result)}"
        ordinary = re.fullmatch(r"(.+?[\s*])(\w+)(?:\[([^]]+)\])?", text)
        if not ordinary:
            raise ValueError(f"unsupported interface declaration: {text}")
        result, name, count = ordinary.groups()
        result = ctype(result)
        if count:
            if count == "CRUST_T_UNIT + 1":
                count = str(enums["CrustTypeKind"].index("CRUST_T_UNIT") + 1)
            if not count.isdecimal():
                raise ValueError(f"unsupported interface array: {text}")
            result = f"[{result}; {count}]"
        return name, result

    for stem, source in headers.items():
        lines = [
            "// SPDX-License-Identifier: Apache-2.0",
            "",
            "// Generated by tools/api.py. The layouts apply to this package version.",
            "",
            f'const CRUST_ABI_{stem}: *u8 = "{abi}";',
            "",
        ]
        for _body, name in re.findall(r"typedef enum\s*\{(.*?)\}\s*(\w+)\s*;", source, re.S):
            for index, value in enumerate(enums[name]):
                lines.append(f"const {value}: u32 = {index}u32;")
            lines.append("")
        record_pattern = r"(?:typedef\s+)?struct\s*(\w+)?\s*\{(.*?)\}\s*(\w+)?\s*;"
        for before, body, after in re.findall(record_pattern, source, re.S):
            name = after or before
            if name in OPAQUE:
                continue
            lines.append(f"record {name} {{")
            for field in body.split(";"):
                if field.strip():
                    field_name, field_type = declaration(field)
                    lines.append(f"    {field_name}: {field_type};")
            lines.extend(["}", ""])
        if stem == "crust0_x64":
            model = ROOT / "stages/asm/model.crs"
            model_text = "\n".join(lines).rstrip() + "\n"
            publish(model, model_text, args.check)
        remaining = re.sub(record_pattern, "", source, flags=re.S)
        remaining = re.sub(r"typedef enum\s*\{.*?\}\s*\w+\s*;", "", remaining, flags=re.S)
        remaining = re.sub(r"typedef struct \w+ \w+\s*;", "", remaining)
        remaining = re.sub(r"extern const CrustX64Ops crust_x64_default_ops\s*;", "", remaining)
        for prototype in remaining.split(";"):
            prototype = " ".join(prototype.split())
            if not prototype:
                continue
            match = re.fullmatch(r"(.+?[\s*])(\w+)\((.*)\)", prototype)
            if not match:
                raise ValueError(f"unsupported interface prototype: {prototype}")
            result, name, arguments = match.groups()
            if name in C_ONLY:
                continue
            params = (
                [declaration(arg) for arg in arguments.split(",")] if arguments != "void" else []
            )
            rendered = ", ".join(f"{param}: {kind}" for param, kind in params)
            lines.append(f'extern fn {name}({rendered}) -> {ctype(result)} = "{name}";')
        output = "\n".join(lines).rstrip() + "\n"
        path = ROOT / "api" / f"{stem}.crs"
        publish(path, output, args.check)


if __name__ == "__main__":
    main()
